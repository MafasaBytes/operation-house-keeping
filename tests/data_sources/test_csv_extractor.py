"""Tests for the format-aware, pre-semantic CSV extractor."""

import pytest

from backend.data_sources.contracts import ExtractionError
from backend.data_sources.extractors import CsvExtractionConfig, extract_csv

RAW_RECORD_ID = "a" * 32

VALID_CSV = (
    b"item_no,name,quantity,unit,parent\n"
    b'100-001,"Frame, welded",1,piece,\n'
    b"100-002,Bolt M6,8,piece,100-001\n"
)


class TestHappyPath:
    def test_header_comes_from_configured_row(self):
        table = extract_csv(VALID_CSV, RAW_RECORD_ID, CsvExtractionConfig())
        assert table.columns == ["item_no", "name", "quantity", "unit", "parent"]
        assert table.header_row_index == 0

    def test_values_stay_strings_and_quoted_commas_survive(self):
        table = extract_csv(VALID_CSV, RAW_RECORD_ID, CsvExtractionConfig())
        first = table.rows[0]
        assert first.cells[1].value == "Frame, welded"
        assert first.cells[2].value == "1"  # not int(1)

    def test_every_cell_traces_to_raw_location(self):
        table = extract_csv(VALID_CSV, RAW_RECORD_ID, CsvExtractionConfig())
        bolt_qty = table.rows[1].cells[2]
        assert bolt_qty.raw_record_id == RAW_RECORD_ID
        assert bolt_qty.physical_row_index == 2  # 0-based, header is row 0
        assert bolt_qty.column_index == 2
        assert bolt_qty.column_name == "quantity"
        assert bolt_qty.value == "8"

    def test_empty_field_is_none_not_empty_string(self):
        table = extract_csv(VALID_CSV, RAW_RECORD_ID, CsvExtractionConfig())
        assert table.rows[0].cells[4].value is None  # parent of the root item

    def test_no_type_or_unit_guessing_units_stay_in_their_column(self):
        table = extract_csv(VALID_CSV, RAW_RECORD_ID, CsvExtractionConfig())
        assert table.rows[0].cells[3].value == "piece"


class TestHeaderConfiguration:
    def test_header_row_can_be_moved_explicitly(self):
        payload = b"generated by tool X\nitem_no,name\n100-001,Frame\n"
        table = extract_csv(
            payload, RAW_RECORD_ID, CsvExtractionConfig(header_row_index=1)
        )
        assert table.columns == ["item_no", "name"]
        assert table.rows[0].physical_row_index == 2
        assert "row 0" in " ".join(table.warnings).lower() or table.warnings

    def test_missing_header_row_raises(self):
        with pytest.raises(ExtractionError) as excinfo:
            extract_csv(b"", RAW_RECORD_ID, CsvExtractionConfig())
        assert excinfo.value.error_code == "EXTRACT_NO_HEADER_ROW"


class TestFailuresAndWarnings:
    def test_undecodable_payload_raises_typed_error(self):
        with pytest.raises(ExtractionError) as excinfo:
            extract_csv(b"\xff\xfe\x00broken", RAW_RECORD_ID, CsvExtractionConfig())
        assert excinfo.value.error_code == "EXTRACT_UNDECODABLE"

    def test_ragged_short_row_yields_warning_and_keeps_cells(self):
        payload = b"item_no,name,quantity\n100-001,Frame\n"
        table = extract_csv(payload, RAW_RECORD_ID, CsvExtractionConfig())
        assert any("expected 3" in w and "found 2" in w for w in table.warnings)
        row = table.rows[0]
        assert [c.value for c in row.cells] == ["100-001", "Frame"]

    def test_ragged_long_row_yields_warning_and_preserves_extra_values(self):
        payload = b"item_no,name\n100-001,Frame,unexpected\n"
        table = extract_csv(payload, RAW_RECORD_ID, CsvExtractionConfig())
        assert any("expected 2" in w and "found 3" in w for w in table.warnings)
        extra = table.rows[0].cells[2]
        assert extra.value == "unexpected"
        assert extra.column_name == "__column_2__"  # placeholder, clearly synthetic

    def test_duplicate_header_names_yield_warning(self):
        payload = b"item_no,item_no\n1,2\n"
        table = extract_csv(payload, RAW_RECORD_ID, CsvExtractionConfig())
        assert any("duplicate" in w.lower() for w in table.warnings)
